export const LEAGUE_BY_ID: Map<string, League> = new Map(
  LEAGUES.map((league) => [league.id, league]),
);

const REGION_ORDER: Record<RegionId, number> = {
  brasil: 0,
  internacional: 1,
  europa: 2,
  americas: 3,
  mundo: 4,
};

export function orderedLeagues(region?: string): League[] {
  const list =
    region && region !== "todos"
      ? LEAGUES.filter((league) => league.region === region)
      : LEAGUES.slice();
  return list.sort((a, b) => {
    const regionDiff = REGION_ORDER[a.region] - REGION_ORDER[b.region];
    if (regionDiff !== 0) return regionDiff;
    return a.priority - b.priority;
  });
}
