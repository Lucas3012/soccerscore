const MAP = new Map<string, CountryInfo>();
for (const league of LEAGUES) {
  if (!MAP.has(league.country)) MAP.set(league.country, { flag: league.flag, region: league.region });
}
for (const [name, info] of Object.entries(EXTRA)) {
  if (!MAP.has(name)) MAP.set(name, info);
}

export function countryInfo(country: string): CountryInfo {
  return MAP.get(country) ?? { flag: "🌍", region: "mundo" };
}
